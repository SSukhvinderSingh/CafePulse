import { Sparkles, Cpu } from 'lucide-react';

/** Reveals whether content came from live Gemini or the deterministic mock engine. */
export function SourceBadge({ source }) {
  const live = source === 'gemini';
  const Icon = live ? Sparkles : Cpu;
  return (
    <span
      className={`inline-flex items-center gap-1 rounded-full px-2 py-0.5 font-mono text-[10px] uppercase tracking-wider ${live ? 'bg-amber-500 text-espresso-950' : 'border border-crema-300/40 text-crema-200'}`}
      title={live ? 'Generated by Gemini' : 'Generated by the offline mock engine'}
    >
      <Icon size={11} aria-hidden="true" />
      {live ? 'Gemini' : 'Mock'}
    </span>
  );
}

const STATUS_STYLE = {
  in: 'bg-matcha-500/20 text-[#b9d9a6] border-matcha-500/50',
  low: 'bg-amber-500/20 text-amber-400 border-amber-500/50',
  out: 'bg-terracotta-500/20 text-[#f1a597] border-terracotta-500/50',
};
const STATUS_LABEL = { in: 'In stock', low: 'Low', out: 'Out' };
const STATUS_GLYPH = { in: '●', low: '◐', out: '○' };

/** Colour + glyph + text so status never relies on colour alone. */
export function InventoryBadge({ status }) {
  return (
    <span className={`inline-flex items-center gap-1 rounded-md border px-1.5 py-0.5 text-[11px] font-medium ${STATUS_STYLE[status]}`}>
      <span aria-hidden="true">{STATUS_GLYPH[status]}</span>
      {STATUS_LABEL[status]}
    </span>
  );
}
